"""Build stages/data.js for the creative-refinement review sketches.

It copies, without change, the approved geometry the sketches need:
- the six approved Doomscript inscriptions, laid out from the traced glyphs exactly as
  web/src/lib/runes.ts lays them out (one rune per letter, the same advances and gap);
- the marks exported from the approved board generator (web/src/marks/*.ts).

Nothing here is redrawn. Run from the repository root:
    python design/explorations/creative-refinement-1/source/build_data.py
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
OUT = os.path.join(os.path.dirname(__file__), "..", "stages", "data.js")

glyphs = json.load(open(os.path.join(ROOT, "web/src/data/doomscript-glyphs.json"), encoding="utf-8"))["glyphs"]

INSCRIPTIONS = [
    "there is no promise of tomorro",
    "to the viktor go the spoils",
    "justice",
    "revenge",
    "viktor von doom",
    "latveria",
]
LETTERS = {c: c for c in "acdefghijlmnoprstuv"}
LETTERS["k"] = "k"
LETTERS["q"] = "k"
SPACE, HEIGHT, GAP = 46, 100, 0.28


def rune_line(text):
    seq = []
    for ch in text.lower():
        if ch == " ":
            seq.append(("space", SPACE))
        elif ch == ".":
            seq.append(("dot", SPACE))
        elif ch in LETTERS:
            key = LETTERS[ch]
            seq.append((key, glyphs[key]["advance"]))
        else:
            raise SystemExit(f'Doomscript has no rune for "{ch}" in "{text}"')
    x, out, dots = 0.0, [], []
    for key, adv in seq:
        if key == "dot":
            dots.append([round(x + adv / 2, 2), HEIGHT / 2, HEIGHT * 0.07])
        elif key != "space":
            out.append([round(x, 2), glyphs[key]["path"]])
        x += adv + GAP * HEIGHT
    return {"w": round(x - GAP * HEIGHT, 2), "h": HEIGHT, "g": out, "dots": dots}


marks = {}
for name in ["sealMark", "maskLevel1", "maskLevel2Plain", "suitRuneLevel1", "suitRuneLevel2",
             "cuirassTile", "cuirassTileEmpty", "nestedSquare", "bolt"]:
    src = open(os.path.join(ROOT, "web/src/marks", f"{name}.ts"), encoding="utf-8").read()
    data = json.loads(re.search(r"=\s*(\{.*\});?\s*$", src, re.S).group(1))
    marks[name] = data

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by source/build_data.py from the approved glyphs and marks. Do not edit.\n")
    f.write("window.RUNES = " + json.dumps({t: rune_line(t) for t in INSCRIPTIONS}) + ";\n")
    f.write("window.MARKS = " + json.dumps(marks) + ";\n")
print("wrote", os.path.relpath(OUT, ROOT), os.path.getsize(OUT), "bytes")
